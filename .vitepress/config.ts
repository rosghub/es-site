const siteUrl = "https://estimatesync.com";
const defaultShareImage = "/banners/estimating-banner.png";
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, "../..");
const supportAssistantPath = path.join(
  projectRoot,
  "src/components/support/DocsSupportAssistantRoot.tsx"
);
// This folder also builds on its own from the es-site repo, which has no React
// app. Those builds are previews, so they skip the Google tag, ask search
// engines not to index them, and render no support assistant.
const isStandalone = !fs.existsSync(supportAssistantPath);
const docsEnvMode = process.env.PQP_DOCS_ENV;
const docsEnv = docsEnvMode ? loadEnv(docsEnvMode, projectRoot, "VITE_") : {};
// Only production builds report. Staging builds set PQP_DOCS_ENV, and `npm run
// dev` serves a docs build, so it sets PQP_DOCS_SKIP_GOOGLE_TAG.
const loadsGoogleTag =
  !isStandalone &&
  !docsEnvMode && !process.env.PQP_DOCS_SKIP_GOOGLE_TAG && !process.argv.includes("dev");
const appLandingPath = "/paint-estimate-app";
const appLandingHref = process.argv.includes("dev")
  ? `${process.env.PQP_APP_ORIGIN ?? "http://127.0.0.1:5173"}${appLandingPath}`
  : appLandingPath;
const docsEnvDefine = Object.fromEntries(
  Object.entries(docsEnv).map(([key, value]) => [
    `import.meta.env.${key}`,
    JSON.stringify(value),
  ])
);

// YAML reads an unquoted 2026-10-22 as a Date, so keep article dates as
// plain YYYY-MM-DD strings for the byline and structured data.
function toDateString(value: unknown): string | undefined {
  if (value instanceof Date) {
    return value.toISOString().slice(0, 10);
  }
  return typeof value === "string" ? value : undefined;
}

